/**
 * Extract keywords from a message for tool pattern learning
 */
export function extractKeywords(message: string): string[] {
  return message
    .toLowerCase()
    .replace(/[^\w\s]/g, ' ')
    .split(/\s+/)
    .filter((word) => word.length > 2 && !STOP_WORDS.has(word))
    .slice(0, 20);
}
